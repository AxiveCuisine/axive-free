// Builds the graphical interface (gui/) into one generated module the core
// carries: src/gui/bundle.generated.ts (every file, base64, with its type).
// The window is served from memory, so a lone Axive.exe needs nothing else.
//   node scripts/build-gui.mjs [--dev]   (--dev: readable, with source maps)
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import * as esbuild from 'esbuild'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const dev = process.argv.includes('--dev')
const out = path.join(root, 'gui', 'dist')
// Axive Free builds this same window: its package name says which edition this is
const edition = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).name === 'axive-free' ? 'free' : 'axive'
// the fonts and the mark: Axive keeps them with its site, Free beside the window
const asset = (name, site) => [path.join(root, 'gui', 'fonts', name), path.join(root, 'site', 'public', site)].find(p => fs.existsSync(p)) ?? path.join(root, 'site', 'public', site)
fs.rmSync(out, {recursive: true, force: true})

const result = await esbuild.build({
  entryPoints: {app: path.join(root, 'gui', 'src', 'main.tsx')},
  bundle: true,
  outdir: out,
  format: 'iife',
  platform: 'browser',
  target: ['chrome120'],
  jsx: 'automatic',
  minify: !dev,
  sourcemap: dev ? 'inline' : false,
  legalComments: 'none',
  external: ['/fonts/*'],
  define: {'process.env.NODE_ENV': JSON.stringify(dev ? 'development' : 'production'), __AXIVE_EDITION__: JSON.stringify(edition)},
  logLevel: 'warning',
  metafile: true,
})
if (result.errors.length) process.exit(1)

const files = {
  '/index.html': [path.join(root, 'gui', 'index.html'), 'text/html; charset=utf-8'],
  '/app.js': [path.join(out, 'app.js'), 'text/javascript; charset=utf-8'],
  '/app.css': [path.join(out, 'app.css'), 'text/css; charset=utf-8'],
  '/favicon.svg': [asset('favicon.svg', 'favicon.svg'), 'image/svg+xml'],
  '/fonts/cormorant.woff2': [asset('cormorant.woff2', 'fonts/cormorant.woff2'), 'font/woff2'],
  '/fonts/cormorant-italic.woff2': [asset('cormorant-italic.woff2', 'fonts/cormorant-italic.woff2'), 'font/woff2'],
  '/fonts/cormorant-sc-500.woff2': [asset('cormorant-sc-500.woff2', 'fonts/cormorant-sc-500.woff2'), 'font/woff2'],
  '/fonts/source-serif-4.woff2': [path.join(root, 'gui', 'fonts', 'source-serif-4.woff2'), 'font/woff2'],
}
const lines = Object.entries(files).map(([url, [file, type]]) => {
  const body = fs.readFileSync(file).toString('base64')
  return `  ${JSON.stringify(url)}: {type: ${JSON.stringify(type)}, body: ${JSON.stringify(body)}},`
})
fs.writeFileSync(
  path.join(root, 'src', 'gui', 'bundle.generated.ts'),
  `// generated by scripts/build-gui.mjs: do not edit\nexport const ASSETS: Record<string, {type: string; body: string}> = {\n${lines.join('\n')}\n}\n`,
)
const size = Object.values(files).reduce((sum, [file]) => sum + fs.statSync(file).size, 0)
console.log(`gui (${edition}): ${Object.keys(files).length} files, ${(size / 1024).toFixed(0)} KB${dev ? ' (dev)' : ''}`)
